#!/usr/bin/env python3
"""Install Git's pre-push config hook in Claude's Bash environment and report setup."""
import contextlib
import importlib.util
import json
import os
from pathlib import Path
import re
import shlex
import sys
import tempfile


# Resumed sessions can still have 2.4/2.5.0 state in their shell. Keep the
# order and empty entries of PATH, including directories containing spaces.
_RETIRE_SHIMS = r"""_sw_rest=${PATH-}
_sw_path=
_sw_sep=
while :; do
    _sw_entry=${_sw_rest%%:*}
    _sw_dir=${_sw_entry:-.}
    case "/${_sw_dir%/}" in
        */software-workflows/hooks/gitshim|*/software-workflows/*/hooks/gitshim) ;;
        *)
            if [ ! -f "$_sw_dir/.codex-gate-farm" ] && ! {
                [ -f "$_sw_dir/git" ] && [ -f "$_sw_dir/../push_gate.py" ]
            }; then
                _sw_path="$_sw_path$_sw_sep$_sw_entry"
                _sw_sep=:
            fi ;;
    esac
    case $_sw_rest in
        *:*) _sw_rest=${_sw_rest#*:} ;;
        *) break ;;
    esac
done
export PATH="$_sw_path"
if [ -n "${GIT_EXEC_PATH-}" ] && [ -f "$GIT_EXEC_PATH/.codex-gate-farm" ]; then
    unset GIT_EXEC_PATH
fi
if [ -n "${BASH_VERSION-}" ]; then
    for _sw_name in "${!CODEX_GATE_@}"; do unset "$_sw_name"; done
elif [ -n "${ZSH_VERSION-}" ]; then
    unset -m 'CODEX_GATE_*'
else
    for _sw_name in $(command -p env | command -p sed -n 's/^\(CODEX_GATE_[A-Za-z0-9_]*\)=.*/\1/p'); do
        unset "$_sw_name"
    done
fi
unset _sw_rest _sw_path _sw_sep _sw_entry _sw_dir _sw_name
"""


# Read the count when Claude sources the env file. Other SessionStart hooks,
# the parent shell and previous sources of this file can all have added config.
# The only interpolation into eval is an integer index generated by this loop.
_CONFIG = """\
_sw_push_config() {
    _sw_i=0
    _sw_n=${GIT_CONFIG_COUNT:-0}
    case $_sw_n in *[!0-9]*) return 1 ;; esac
    while [ "$_sw_i" -lt "$_sw_n" ]; do
        eval "_sw_key=\\${GIT_CONFIG_KEY_${_sw_i}-}"
        eval "_sw_value=\\${GIT_CONFIG_VALUE_${_sw_i}-}"
        if [ "$_sw_key" = "$1" ] && [ "$_sw_value" = "$2" ]; then
            return
        fi
        _sw_i=$((_sw_i + 1))
    done
    export "GIT_CONFIG_KEY_$_sw_i=$1" "GIT_CONFIG_VALUE_$_sw_i=$2"
    export GIT_CONFIG_COUNT=$((_sw_i + 1))
}
"""


def _install(data, git):
    if os.name == "nt":
        return "The Bash push review gate is inactive on Windows."
    env_file = os.environ.get("CLAUDE_ENV_FILE")
    if not env_file:
        return "The push review gate is inactive because Claude did not supply its Bash env file."
    hook = Path(__file__).resolve().with_name("push_review.py")
    command = shlex.join([sys.executable, "-I", str(hook), "--git", git or "git"])
    session = str(data.get("session_id") or "")
    block = (_CONFIG
             + "_sw_push_config hook.software-workflows-review.command " + shlex.quote(command) + "\n"
             + "_sw_push_config hook.software-workflows-review.event pre-push\n"
               "unset -f _sw_push_config\nunset _sw_i _sw_n _sw_key _sw_value\n")
    if re.fullmatch(r"[A-Za-z0-9_-]{1,128}", session):
        block += 'export CLAUDE_CODE_SESSION_ID="${CLAUDE_CODE_SESSION_ID:-' + session + '}"\n'

    # Claude keeps this hook's own env file across plugin upgrades. An atomic
    # replacement also prevents a concurrent Bash call from sourcing half a block.
    try:
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(os.path.abspath(env_file)), prefix=".sw-env-")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as fh:
                # A still-live Bash shell may already have sourced an old file.
                # A fresh shell pays only this shell-builtin check per command.
                fh.write('case ":${PATH-}:" in */hooks/gitshim:*) _sw_old=1 ;; *) _sw_old= ;; esac\n'
                         'if [ -n "${_sw_old}${CODEX_GATE_STATE-}${CODEX_GATE_SESSION-}${GIT_EXEC_PATH-}" ]; then\n'
                         + _RETIRE_SHIMS + 'fi\nunset _sw_old\n' + block)
            os.replace(tmp, env_file)
        finally:
            with contextlib.suppress(FileNotFoundError):
                os.unlink(tmp)
    except OSError:
        # Some hosts allow appending to the file but not replacing its inode.
        # Run last, after every historical block that put a shim back on PATH.
        with open(env_file, "a", encoding="utf-8") as fh:
            fh.write("\n" + _RETIRE_SHIMS + block)
    return ""


def main():
    data = json.loads(sys.stdin.read(1 << 20) or "{}")
    path = Path(__file__).resolve().parents[1] / "plugin_setup.py"
    spec = importlib.util.spec_from_file_location("sw_plugin_setup", path)
    setup = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(setup)
    # Version detection and the pinned plumbing executable must also work if
    # SessionStart itself inherited the previous session's shim or mirror.
    def legacy_directory(entry):
        path = Path(entry or ".")
        return ((path / ".codex-gate-farm").is_file()
                or (path.name == "gitshim" and path.parent.name == "hooks"
                    and ("software-workflows" in path.parts or (path.parent / "push_gate.py").is_file()))
                or ((path / "git").is_file() and (path / ".." / "push_gate.py").is_file()))
    os.environ["PATH"] = os.pathsep.join(p for p in os.get_exec_path() if not legacy_directory(p))
    git, limit = setup.git_capability()
    try:
        install_notice = _install(data, git)
    except OSError as exc:
        install_notice = f"The push review gate is inactive: could not write Claude's Bash env file ({exc})."
    message = []
    context = []
    if data.get("source") in ("startup", "resume"):
        items = setup.checks(quick=True, git_info=(git, limit))
        missing = [(c[0], c[2]) for c in items if not c[1]]
        if missing:
            message.append("software-workflows: %s not ready. Run /software-workflows:setup"
                           % ", ".join(item for item, _ in missing))
            context.append("software-workflows setup is incomplete on this machine: "
                           + "; ".join(f"{item}: {detail}" for item, detail in missing)
                           + ". Tell the user once, briefly, that /software-workflows:setup explains "
                             "these checks (it asks before changing any setting).")
    # The cleanup's session-start step (cleanup/swclean.py): record this session's cgroup for the
    # timer, note the repository, and install or refresh the stable copy, timer and Codex hooks.
    # It runs inside this hook, not as a second SessionStart entry: Claude keys each SessionStart
    # hook's env file by its position, and a new entry could leave a resumed session sourcing an
    # old file. It never fails the session start.
    with contextlib.suppress(Exception):
        clean_spec = importlib.util.spec_from_file_location(
            "sw_cleanup", Path(__file__).resolve().parents[1] / "cleanup" / "swclean.py")
        cleanup = importlib.util.module_from_spec(clean_spec)
        clean_spec.loader.exec_module(cleanup)
        cleanup.hook_session_start(data)
    limits = [s for s in (limit, install_notice) if s]
    if message or limits:
        print(json.dumps({"systemMessage": " ".join(message + limits),
                          "hookSpecificOutput": {"hookEventName": "SessionStart",
                                                 "additionalContext": " ".join(context + limits)}}))


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        notice = f"software-workflows: the Bash push review gate setup could not be verified ({type(exc).__name__})."
        print(json.dumps({"systemMessage": notice, "hookSpecificOutput": {
            "hookEventName": "SessionStart", "additionalContext": notice}}))
